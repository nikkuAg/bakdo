import AppKit
import ApplicationServices

/// Puts text into whatever field has keyboard focus, in any app, by pasting it and then
/// restoring the user's clipboard. Also reads the current selection for "fix selected text".
enum TextInserter {
    typealias PasteboardSnapshot = [[NSPasteboard.PasteboardType: Data]]

    static func insert(_ text: String, smartSpacing: Bool) {
        var output = text
        if smartSpacing, let previous = characterBeforeCursor() {
            if !previous.isWhitespace && !"([{\"'“‘/@#-".contains(previous) {
                output = " " + output
            }
        }
        paste(output)
    }

    /// Replaces the current selection in the focused app.
    static func replaceSelection(with text: String) {
        paste(text)
    }

    static func copyToClipboard(_ text: String) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
    }

    // MARK: - Reading the selection

    enum SelectionResult {
        case text(String)
        case nothingSelected
    }

    /// Asks Accessibility for the selected text first (no clipboard churn). Apps that don't expose
    /// it (many Electron and web views) fall back to a ⌘C round-trip through the clipboard.
    @MainActor
    static func readSelection() async -> SelectionResult {
        switch accessibilitySelection() {
        case .some(.text(let text)): return .text(text)
        case .some(.nothingSelected): return .nothingSelected
        case .none: break
        }

        let pasteboard = NSPasteboard.general
        let saved = snapshot(pasteboard)
        let before = pasteboard.changeCount
        postKey(8, flags: .maskCommand) // ⌘C
        for _ in 0..<20 where pasteboard.changeCount == before {
            try? await Task.sleep(for: .milliseconds(20))
        }
        let copied = pasteboard.changeCount != before ? pasteboard.string(forType: .string) : nil
        if pasteboard.changeCount != before { restore(saved, to: pasteboard) }
        guard let copied, !copied.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return .nothingSelected }
        return .text(copied)
    }

    /// nil = this app doesn't tell us; otherwise the selected text or an explicit "nothing selected".
    private static func accessibilitySelection() -> SelectionResult? {
        guard let focused = focusedElement() else { return nil }
        var rangeRef: CFTypeRef?
        if AXUIElementCopyAttributeValue(focused, kAXSelectedTextRangeAttribute as CFString, &rangeRef) == .success,
           let rangeRef, CFGetTypeID(rangeRef) == AXValueGetTypeID() {
            var range = CFRange()
            if AXValueGetValue(rangeRef as! AXValue, .cfRange, &range), range.length == 0 {
                return .nothingSelected
            }
        }
        var textRef: CFTypeRef?
        guard AXUIElementCopyAttributeValue(focused, kAXSelectedTextAttribute as CFString, &textRef) == .success,
              let text = textRef as? String, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }
        return .text(text)
    }

    // MARK: - Pasting

    private static func paste(_ text: String) {
        let pasteboard = NSPasteboard.general
        let saved = snapshot(pasteboard)

        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        // Tell clipboard managers not to record this.
        pasteboard.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        pasteboard.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        let ourChange = pasteboard.changeCount

        postKey(9, flags: .maskCommand) // ⌘V

        // Give the target app time to read the pasteboard before putting the old contents back.
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.6) {
            guard pasteboard.changeCount == ourChange else { return }
            restore(saved, to: pasteboard)
        }
    }

    private static func snapshot(_ pasteboard: NSPasteboard) -> PasteboardSnapshot {
        (pasteboard.pasteboardItems ?? []).map { item in
            var entry: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { entry[type] = data }
            }
            return entry
        }
    }

    private static func restore(_ saved: PasteboardSnapshot, to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        guard !saved.isEmpty else { return }
        let items = saved.map { entry -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in entry { item.setData(data, forType: type) }
            return item
        }
        pasteboard.writeObjects(items)
    }

    /// Posts a key with exactly `flags`, ignoring modifiers the user may still be holding
    /// (fn after dictation, ⌃⌥ after the fix shortcut).
    private static func postKey(_ key: CGKeyCode, flags: CGEventFlags) {
        let source = CGEventSource(stateID: .privateState)
        let down = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: false)
        down?.flags = flags
        up?.flags = flags
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    // MARK: - Accessibility helpers

    private static func focusedElement() -> AXUIElement? {
        let system = AXUIElementCreateSystemWide()
        AXUIElementSetMessagingTimeout(system, 0.15)
        var focusedRef: CFTypeRef?
        guard AXUIElementCopyAttributeValue(system, kAXFocusedUIElementAttribute as CFString, &focusedRef) == .success,
              let focusedRef, CFGetTypeID(focusedRef) == AXUIElementGetTypeID() else { return nil }
        let focused = focusedRef as! AXUIElement
        AXUIElementSetMessagingTimeout(focused, 0.15)
        return focused
    }

    /// Reads the character just before the insertion point through the Accessibility API.
    /// Returns nil when the app doesn't expose it (many web views and Electron apps don't).
    private static func characterBeforeCursor() -> Character? {
        guard let focused = focusedElement() else { return nil }
        var rangeRef: CFTypeRef?
        guard AXUIElementCopyAttributeValue(focused, kAXSelectedTextRangeAttribute as CFString, &rangeRef) == .success,
              let rangeRef, CFGetTypeID(rangeRef) == AXValueGetTypeID() else { return nil }
        var range = CFRange()
        guard AXValueGetValue(rangeRef as! AXValue, .cfRange, &range) else { return nil }
        guard range.location > 0 else { return "\n" } // start of field: no leading space

        var previous = CFRange(location: range.location - 1, length: 1)
        guard let previousValue = AXValueCreate(.cfRange, &previous) else { return nil }
        var stringRef: CFTypeRef?
        guard AXUIElementCopyParameterizedAttributeValue(focused, kAXStringForRangeParameterizedAttribute as CFString,
                                                         previousValue, &stringRef) == .success,
              let string = stringRef as? String else { return nil }
        return string.last
    }

    /// Name of the app that currently has focus, for the history list.
    static func frontmostAppName() -> String? {
        NSWorkspace.shared.frontmostApplication?.localizedName
    }
}
